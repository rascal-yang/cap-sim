"""Frozen-contract contact reference tracking with online SONIC mode1.

Source rows are POST-step states with the ctrl used for that step. Boundaries
share states, not control ticks. Only initial qpos/qvel are restored; all later
states are generated by mj_step. This is an action-replay baseline, not transfer.
"""
import argparse
import hashlib
import json
from datetime import datetime
from pathlib import Path
from types import SimpleNamespace
from zoneinfo import ZoneInfo
import time
import numpy as np


def now():return datetime.now(ZoneInfo('Asia/Shanghai')).isoformat(timespec='seconds')
def sha(p):return hashlib.sha256(Path(p).read_bytes()).hexdigest()
def write(p,x):
    with Path(p).open('x') as f:json.dump(x,f,indent=2,allow_nan=False)


def finger_schedule(prefix,program,steps):
    """Reconstruct original commanded fingers, not measured finger positions."""
    prefix=np.asarray(prefix,float)
    if prefix.shape!=(250,14) or not np.isfinite(prefix).all():raise ValueError('Need original 250 hand commands')
    chunks=[np.repeat(prefix,4,axis=0)];last=prefix[-1].copy()
    for action in program:
        n=round(action['duration_s']/.005)
        end=np.r_[action.get('left_fingers',last[:7]),action.get('right_fingers',last[7:])]
        u=np.arange(1,n+1)/n;alpha=u*u*(3-2*u)
        chunks.append(last+(end-last)*alpha[:,None]);last=end.copy()
    result=np.concatenate(chunks)
    if steps>len(result):raise ValueError('Missing command support')
    return result[:steps]


def check_contract(path):
    path=Path(path).resolve();r=json.loads(path.read_text())
    if sha(path)!=(path.parent/'experiment.sha256').read_text().strip():raise ValueError('Contract not frozen')
    if r['record_status']!='frozen_ready' or not r['preflight']['passed']:raise ValueError('Preflight incomplete')
    if r['control']['fallback_allowed'] or r['budget']['attempts_per_case']!=1:raise ValueError('Wrong execution scope')
    if r['control']['actual_mode']!='prefix_torque_then_sonic_mode1':raise ValueError('Unexpected control mode')
    hashes=r['preflight']['evidence_sha256']
    if str(Path(__file__).resolve()) not in hashes:raise ValueError('Executor source not bound')
    for key in ('model','initial','controls','reference_states','reference_evidence','task','targets','source_controller'):
        if r['inputs'][key] not in hashes:raise ValueError('Unbound input: '+key)
    if r['runtime']['actual_loaded_session_evidence'] not in hashes:raise ValueError('Unbound runtime')
    for name,digest in hashes.items():
        if sha(name)!=digest:raise ValueError('Frozen evidence changed: '+name)
    runtime=json.loads(Path(r['runtime']['actual_loaded_session_evidence']).read_text())
    if not runtime['passed'] or not runtime['sessions_loaded'] or len(runtime['actual_session_providers'])!=3:raise ValueError('Missing loaded sessions')
    if any(p!=['CPUExecutionProvider'] for p in runtime['actual_session_providers'].values()):raise ValueError('Unexpected provider')
    if runtime['versions']['tensorrt']!='10.13.0.35' or runtime['versions']['onnxruntime']!='1.23.2':raise ValueError('Wrong runtime')
    return r


def measurement(m,d):
    import mujoco
    from cap_sim.backends.humano import Backend
    obj=m.body('apple_001').id;table=m.geom('table_geom').id
    c=Backend.contacts(SimpleNamespace(m=m,d=d,mj=mujoco,object_ids={'target':obj}))
    bottom=float('inf')
    for g in np.flatnonzero(m.geom_bodyid==obj):
        if not (m.geom_contype[g] or m.geom_conaffinity[g]):continue
        if m.geom_type[g]!=mujoco.mjtGeom.mjGEOM_MESH:raise ValueError('Unexpected apple geometry')
        mid=int(m.geom_dataid[g]);a=int(m.mesh_vertadr[mid]);n=int(m.mesh_vertnum[mid])
        verts=m.mesh_vert[a:a+n]@d.geom_xmat[g].reshape(3,3).T+d.geom_xpos[g]
        bottom=min(bottom,float(verts[:,2].min()))
    top=float(d.geom_xpos[table,2]+m.geom_size[table,2]);right=m.body('right_wrist_yaw_link').id
    return {'contacts':c,'clearance_m':bottom-top,'object_pose':np.r_[d.xpos[obj],d.xquat[obj]].tolist(),
            'right_pose':np.r_[d.xpos[right],d.xquat[right]].tolist(),
            'root_pose':d.qpos[:7].tolist()}


def initialize_source(m,d,initial):
    """Historical HybridBackend reset: forward, then restore solver warmstart."""
    import mujoco
    for key,size in [('qpos',m.nq),('qvel',m.nv),('ctrl',m.nu),('qacc_warmstart',m.nv)]:
        if key not in initial or np.asarray(initial[key]).shape!=(size,) or not np.isfinite(initial[key]).all():
            raise ValueError('Missing or invalid initial state: '+key)
    mujoco.mj_resetData(m,d)
    d.qpos[:]=initial['qpos'];d.qvel[:]=initial['qvel'];d.ctrl[:]=initial['ctrl'];d.time=0.
    mujoco.mj_forward(m,d)
    d.qacc_warmstart[:]=initial['qacc_warmstart']


def run(contract):
    import mujoco
    r=check_contract(contract);root=Path(contract).resolve().parent;out=root/'execution';out.mkdir(exist_ok=False)
    from cap_sim.backends.humano import Backend
    from cap_sim.backends.native_sonic import Sonic,rot
    from humano.mt.base import MotorCommand
    from humano.core.action import ActionCmd
    from .privileged import no_physics
    backend=Backend();task=json.loads(Path(r['inputs']['task']).read_text())
    with no_physics():backend.describe(task)
    m,d=backend.m,backend.d
    frozen=json.loads(Path(r['physics']['physics_parameters_manifest']).read_text())
    for key,value in frozen['arrays'].items():
        if not np.array_equal(getattr(m,key),np.asarray(value)):raise ValueError('Physics differs: '+key)
    sonic=Sonic(m,backend.robot,task['resources']['sonic_models'],backend.initial)
    providers={key:getattr(sonic,key).get_providers() for key in ('encoder','decoder','planner')}
    if any(v!=['CPUExecutionProvider'] for v in providers.values()):raise ValueError('Provider mismatch')
    write(out/'actual_providers.json',providers)
    targets=np.load(r['inputs']['targets']);source_controller=json.loads(Path(r['inputs']['source_controller']).read_text())
    tracking=[];commands=[];target=None;handoff=None
    initial=np.load(r['inputs']['initial'],allow_pickle=False)
    controls=np.load(r['inputs']['controls'],allow_pickle=False)['ctrl']
    if (m.na or m.nmocap or m.nu!=43 or abs(m.opt.timestep-.005)>1e-12):raise ValueError('Unsupported model')
    if controls.shape!=(r['inputs']['steps'],m.nu) or not np.isfinite(controls).all():raise ValueError('Invalid command sequence')
    initialize_source(m,d,initial)
    if np.any(d.qfrc_applied) or np.any(d.xfrc_applied):raise ValueError('Unexpected applied force')
    dt=float(m.opt.timestep);start=now();tick=time.perf_counter();states=[];observations=[];failure=None;bad=lost=contact_duration=0.;steps=0
    boundaries=r['inputs']['boundaries'];gates=[];stage='prefix';caught=None
    write(out/'initial_observation.json',measurement(m,d));np.savez_compressed(out/'actual_initial.npz',qpos=d.qpos.copy(),qvel=d.qvel.copy(),ctrl=d.ctrl.copy(),qacc_warmstart=d.qacc_warmstart.copy())
    try:
        for i,ctrl in enumerate(controls):
            # Boundary state at source index k was produced by command k. Next command is k+1.
            for phase,source_index in boundaries.items():
                if i!=source_index+1:continue
                ob=measurement(m,d);c=ob['contacts'];passed=True
                if phase=='lift':passed=contact_duration>=.12 and c['hand_object_N']>.1
                if phase=='hold':passed=c['hand_object_N']>.1 and ob['clearance_m']>=.03
                gates.append({'phase':phase,'time_s':float(d.time),'passed':bool(passed),'hand_contact_s':contact_duration,'observation':ob})
                if not passed:failure=phase+'_entry_gate';break
                stage=phase
            if failure:break
            if i<1600:
                # Maintain the ten-frame policy observation history at original 50Hz
                # while the certified physical prefix remains bitwise unchanged.
                if i%4==0:
                    sonic.history.append({'omega':d.qvel[3:6].copy(),'q':(d.qpos[sonic.qids]-sonic.default)[sonic.order],
                        'dq':d.qvel[sonic.vids][sonic.order].copy(),'last':sonic.last.copy(),'gravity':rot(d.qpos[3:7]).inv().apply([0,0,-1])})
                    body=np.asarray(source_controller[i//4]['target'])
                    sonic.last=((body-sonic.default)/sonic.scale)[sonic.order];sonic.tick+=1
                d.ctrl[:]=ctrl
            else:
                j=i-1 # desired pose at inference instant, not future post-step state
                if i%4==0:
                    wrists=[(targets[side+'_pose'][j,:3],targets[side+'_pose'][j,3:]) for side in ('left','right')]
                    torso=targets['torso_pose'][j];rootpose=targets['root_pose'][j]
                    if not .4<=rootpose[2]<=.85:raise ValueError('Pelvis target outside interface')
                    if handoff is None:
                        reference=np.load(r['inputs']['reference_states'])['samples'][1599]
                        handoff={'time_s':float(d.time),'prefix_qpos_max_error':float(abs(d.qpos-reference[1:1+m.nq]).max()),
                            'prefix_qvel_max_error':float(abs(d.qvel-reference[1+m.nq:1+m.nq+m.nv]).max()),'sonic_tick':sonic.tick,'history_length':len(sonic.history)}
                        write(out/'handoff.json',handoff)
                        if handoff['prefix_qpos_max_error']>1e-10 or handoff['prefix_qvel_max_error']>1e-10:raise ValueError('Prefix failed exact-state check')
                    target=sonic.step(d,wrists,(torso[:3],torso[3:]),np.zeros(2),float(rootpose[2]),None,float(rot(rootpose[3:]).as_euler('xyz')[2]))
                    if sonic.records[-1]['mode']!=1:raise RuntimeError('Unexpected mode')
                    row={'time_s':float(d.time),'target_frame':j,'stage':stage,'mode':1,'root_target':rootpose.tolist(),'root_actual':d.qpos[:7].tolist()}
                    for side,bid,(p,q) in zip(('left','right'),(backend.left,backend.right),wrists):
                        row[side]={'target_pose':np.r_[p,q].tolist(),'actual_pose':np.r_[d.xpos[bid],d.xquat[bid]].tolist(),
                            'position_error_m':float(np.linalg.norm(d.xpos[bid]-p)),'orientation_error_rad':float((rot(q).inv()*rot(d.xquat[bid])).magnitude())}
                    tracking.append(row)
                fingers=targets['fingers'][i]
                backend.robot.apply_action(ActionCmd('wbc_torque',low_cmd=MotorCommand(q_target=target,kp=sonic.kp,kd=sonic.kd),use_sensor=False,
                    left_hand_cmd=MotorCommand.hand_command(fingers[:7]),right_hand_cmd=MotorCommand.hand_command(fingers[7:])))
                commands.append({'time_s':float(d.time),'mode':1,'body_target_rad':target.tolist(),'fingers_rad':fingers.tolist(),'ctrl_Nm':d.ctrl.tolist()})
            mujoco.mj_step(m,d);steps+=1;mujoco.mj_forward(m,d)
            ob=measurement(m,d);c=ob['contacts'];ob.update(time_s=float(d.time),stage=stage,source_poststep_frame=i)
            states.append(np.r_[d.time,d.qpos,d.qvel,d.ctrl]);observations.append(ob)
            contact_duration=contact_duration+dt if c['hand_object_N']>.1 else 0.
            bad=bad+dt if c['robot_table_N']>5 else 0.
            lost=lost+dt if stage in ('lift','hold') and c['hand_object_N']<=.1 else 0.
            # Root orientation tilt independent of heading.
            w,x,y,z=d.qpos[3:7];tilt=np.arccos(np.clip(1-2*(x*x+y*y),-1,1))
            if not np.isfinite(d.qpos).all() or not np.isfinite(d.qvel).all():failure='nonfinite_state'
            elif d.qpos[2]<.3 or tilt>np.deg2rad(50):failure='fall'
            elif c['robot_table_N']>50 or bad>=.05-1e-10:failure='unexpected_table_contact'
            elif lost>=.03-1e-10:failure='hand_contact_lost'
            elif any(w.number for w in d.warning):failure='simulation_warning'
            if failure:break
    except Exception as exc:
        failure='execution_exception';caught=repr(exc)
    finally:
        array=np.asarray(states).reshape((-1,1+m.nq+m.nv+m.nu))
        np.savez_compressed(out/'states.npz',samples=array)
        write(out/'observations.json',observations);write(out/'contacts.json',[o['contacts'] for o in observations]);write(out/'gates.json',gates)
        write(out/'execution_audit.json',{'experiment_id':r['experiment_id'],'started_at':start,'ended_at':now(),'contract_sha256':sha(contract),'physics_steps':steps,'recorded_steps':len(states),'missing_measurement_steps':steps-len(states),'mode':'prefix_torque_then_sonic_mode1','sonic_encoder_calls':len(sonic.records),'sonic_decoder_calls':len(sonic.records),'sonic_planner_calls':sonic.serial,'ik_calls':0,'state_initializations':1,'midrun_state_resets':0,'failure':failure,'exception':caught,'completed':steps==len(controls) and not failure,'sim_seconds':float(d.time),'simulation_wall_s':time.perf_counter()-tick,'runtime':'actual CPU SONIC encoder decoder planner; mode1 only after 8s','stage_boundaries_are_state_frames':True})
    write(out/'tracking.json',tracking);write(out/'commands.json',commands);write(out/'controller.json',sonic.records)
    backend.close()
    return {'completed':steps==len(controls) and not failure,'failure':failure,'physics_steps':steps}


def verify(contract):
    """Offline independent acceptance on newly measured states; cannot add physical steps."""
    import mujoco
    from scipy.spatial.transform import Rotation
    from cap_sim.backends.humano import Backend
    from .privileged import no_physics
    r=check_contract(contract);root=Path(contract).resolve().parent;out=root/'execution'
    actual=np.load(out/'states.npz')['samples'];reference=np.load(r['inputs']['reference_states'])['samples'];m=mujoco.MjModel.from_binary_path(r['inputs']['model'])
    obs=json.loads((out/'observations.json').read_text());audit=json.loads((out/'execution_audit.json').read_text());n=len(actual)
    if n==0:raise ValueError('No measured frames')
    position_error=np.asarray([o['right_pose'][:3] for o in obs])-np.load(r['inputs']['reference_evidence'])['right_pose'][:n,:3]
    qerr=actual[:,1:1+m.nq]-reference[:n,1:1+m.nq]
    expected=np.load(r['inputs']['reference_evidence']);op=np.asarray([o['object_pose'] for o in obs]);hp=np.asarray([o['right_pose'] for o in obs]);clear=np.array([o['clearance_m'] for o in obs]);times=actual[:,0]
    hand=np.array([o['contacts']['hand_object_N'] for o in obs]);support=np.array([o['contacts']['support_N'] for o in obs]);table=np.array([o['contacts']['robot_table_N'] for o in obs])
    velocity=np.gradient(op[:,2],times) if n>1 else np.full(n,np.inf)
    hr=Rotation.from_quat(hp[:,[4,5,6,3]]);orr=Rotation.from_quat(op[:,[4,5,6,3]])
    relative=hr.inv().apply(op[:,:3]-hp[:,:3]);rq=(hr.inv()*orr).as_quat()
    lo=r['inputs']['boundaries']['hold'];hi=r['inputs']['hold_end_frame'];covered=hi<n
    stable=np.zeros(n,bool)
    if covered:
        span=slice(lo,hi+1);pd=np.linalg.norm(relative[span]-relative[lo],axis=1);rd=2*np.arccos(np.clip(abs(rq[span]@rq[lo]),0,1))
        stable[span]=(hand[span]>.1)&(support[span]<.1)&(clear[span]>=.03)&(abs(velocity[span])<=.04)&(pd<=.02)&(rd<=.25)
    consecutive=longest=0
    for x in stable:consecutive=consecutive+1 if x else 0;longest=max(longest,consecutive)
    hold_seconds=max(0,longest-1)*m.opt.timestep
    native_backend=Backend()
    try:
        with no_physics():
            task=json.loads(Path(r['inputs']['task']).read_text());native_backend.describe(task)
            for key in ('body_mass','body_inertia','geom_size','geom_pos','geom_quat','geom_friction','actuator_gear','actuator_gainprm','actuator_biasprm'):
                if not np.array_equal(getattr(m,key),getattr(native_backend.m,key)):raise ValueError('Native checker model mismatch: '+key)
            native=native_backend.verify(out)
    finally:native_backend.close()
    phases={}
    bounds=r['inputs']['boundaries']
    for phase,lo2,hi2 in [('grasp',bounds['grasp'],bounds['lift']),('lift',bounds['lift'],bounds['hold']),('hold',bounds['hold'],hi)]:
        covered2=hi2<n;end=min(n,hi2+1);values=np.linalg.norm(position_error[lo2:end],axis=1)
        phases[phase]={'source_frame_start':lo2,'source_frame_end':hi2,'complete':covered2,'executed_samples':max(0,end-lo2),'wrist_position_error_rmse_m':float(np.sqrt(np.mean(values**2))) if len(values) else None,'endpoint_error_m':float(values[-1]) if covered2 else None}
    wrist_error=np.linalg.norm(position_error,axis=1)
    angles=(Rotation.from_quat(hp[:,[4,5,6,3]]).inv()*Rotation.from_quat(expected['right_pose'][:n,[4,5,6,3]])).magnitude()
    result={'success':bool(audit['completed'] and native['success'] and hold_seconds>=1.0 and table.max()<=5 and all(x['complete'] for x in phases.values())),
            'native_acceptance':native,'independent_hold_s':float(hold_seconds),'hold_source_range_covered':covered,'phase_results':phases,
            'max_qpos_component_error':float(np.max(abs(qerr))),'wrist_position_error_m':{'rmse':float(np.sqrt(np.mean(wrist_error**2))),'p95':float(np.percentile(wrist_error,95)),'max':float(wrist_error.max())},
            'wrist_orientation_error_rad':{'rmse':float(np.sqrt(np.mean(angles**2))),'p95':float(np.percentile(angles,95)),'max':float(angles.max())},
            'root_position_error_max_m':float(np.linalg.norm(qerr[:,:3],axis=1).max()),'peak_hand_force_N':float(hand.max()),'peak_robot_table_N':float(table.max()),'robot_table_force_gt_0p1_frames':int(np.sum(table>.1)),
            'maximum_clearance_m':float(clear.max()),'hold_min_clearance_m':float(clear[lo:hi+1].min()) if covered else None,'hold_hand_force_min_N':float(hand[lo:hi+1].min()) if covered else None,
            'hold_relative_translation_drift_m':float(pd.max()) if covered else None,'hold_relative_rotation_drift_rad':float(rd.max()) if covered else None,
            'physics_steps_in_verifier':0,'new_rollout_physics_steps':audit['physics_steps'],'training_ready':False,'no_new_strategy_or_transfer_claim':True}
    write(out/'validation.json',result);return result


